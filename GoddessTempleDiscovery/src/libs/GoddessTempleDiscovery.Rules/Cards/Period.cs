namespace GoddessTempleDiscovery.Rules.Cards;

/// <summary>The periods of Uruk's history, in order, as the Getty chronological table divides them.</summary>
public enum Period
{
    /// <summary>Ubaid period, sixth to fifth millennium BCE; Eanna levels XVIII to XVI.</summary>
    Ubaid,
    /// <summary>Ubaid transitional period, end of the fifth millennium BCE; levels XV to XIII.</summary>
    UbaidTransition,
    /// <summary>Early Uruk period, about 4000 to 3800 BCE; levels XII to X.</summary>
    EarlyUruk,
    /// <summary>Middle Uruk period, about 3800 to 3500 BCE; levels IX to VII.</summary>
    MiddleUruk,
    /// <summary>Late Uruk period, about 3500 to 3300 BCE; levels VI to IV. Monumental architecture, writing.</summary>
    LateUruk,
    /// <summary>Jemdet Nasr period, about 3300 to 3000 BCE; level III.</summary>
    JemdetNasr,
    /// <summary>Early Dynastic periods I to III, about 3000 to 2340 BCE; level I.</summary>
    EarlyDynastic,
    /// <summary>Akkadian period, about 2340 to 2200 BCE.</summary>
    Akkadian,
    /// <summary>Third Dynasty of Ur, about 2112 to 2004 BCE; Ur-Nammu's ziggurat.</summary>
    UrIII,
    /// <summary>Old Babylonian period, about 2025 to 1595 BCE; Sin-kashid.</summary>
    OldBabylonian,
    /// <summary>Middle Babylonian (Kassite) period, about 1650 to 1157 BCE; Karaindash.</summary>
    Kassite,
    /// <summary>Second Dynasty of Isin and the Assyrian kings, 1125 to 625 BCE.</summary>
    IsinIIAndAssyria,
    /// <summary>Neo-Babylonian period, 625 to 539 BCE; Nebuchadnezzar II, Nabonidus.</summary>
    NeoBabylonian,
    /// <summary>Achaemenid period, 538 to 332 BCE; Cyrus the Great.</summary>
    Achaemenid,
    /// <summary>Seleucid period, 332 to 141 BCE; the Resh and Eshgal sanctuaries.</summary>
    Seleucid,
    /// <summary>Parthian period, 141 BCE to 224 CE.</summary>
    Parthian,
    /// <summary>Sassanian period, 224 to 634 CE; Uruk abandoned in the early fourth century.</summary>
    Sassanian,
    /// <summary>The Arab conquest; the battle for al-Warka in 634 CE.</summary>
    ArabConquest,
    /// <summary>The Euphrates shifts west and the land empties, which preserved the ruins.</summary>
    EuphratesShifts,
}
