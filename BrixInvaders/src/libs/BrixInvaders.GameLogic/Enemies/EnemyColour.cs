namespace BrixInvaders.GameLogic;

/// <summary>The four enemy colours. The colour is the point tier: black is worth least, red most.</summary>
public enum EnemyColour
{
    /// <summary>Tier 0 (bottom rows).</summary>
    Black = 0,

    /// <summary>Tier 1.</summary>
    Blue = 1,

    /// <summary>Tier 2.</summary>
    Green = 2,

    /// <summary>Tier 3 (top row).</summary>
    Red = 3,
}
